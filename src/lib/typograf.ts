/* ============================================================
   Мини-типограф для статей, которые приходят данными (JSON):
   авторы пишут обычные пробелы, неразрывные расставляются здесь,
   при рендере. Ручные страницы (.astro) пишут &nbsp; сами — их
   через типограф НЕ гонять.

   Правила сознательно консервативные:
   · nbsp после коротких предлогов/союзов/частиц (в, и, не, для…);
   · nbsp перед длинным тире «—»;
   · nbsp после числа перед словом или числом («5 рабочих дней»).
   Строки могут содержать инлайн-теги <mark> и <a href> — в наших
   href пробелов не бывает, поэтому регэкспы по пробелам их не рвут.
   ============================================================ */

const NBSP = '\u00A0';

const SHORT_WORDS =
  'в|во|и|а|но|к|ко|с|со|у|о|об|на|за|по|до|из|от|не|ни|же|ли|бы|для|при|про|под|над|без|как|что|это|мы|вы|он|она|они|то|уже|ещё|или';

const reShort = new RegExp(`(^|[\\s(«>])(${SHORT_WORDS})\\s+`, 'gi');
const reDash = / —/g;
const reDigit = /(\d)\s(?=[а-яёА-ЯЁ\d])/g;

export function typo(s: string): string {
  return s
    .replace(reShort, (_m, pre, w) => `${pre}${w}${NBSP}`)
    .replace(reDash, `${NBSP}—`)
    .replace(reDigit, `$1${NBSP}`);
}
